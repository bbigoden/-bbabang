/**
 * 결과를 기다리지 않고 보내는 질의.
 *
 * **`then` 을 붙여야 그때 실제로 나간다.** supabase 질의는 만들어 두기만 하면
 * 아무 일도 하지 않는다 — 보낼 것을 적어 둔 쪽지일 뿐이고, `then` 을 부르는
 * 순간에야 통신이 일어난다. 그래서 이렇게 쓰면 요청이 **아예 나가지 않는다**:
 *
 * ```ts
 * void supabase.from('naver_article_views').upsert({ ... })   // ❌ 조용히 아무 일도 안 일어남
 * ```
 *
 * 실제로 매물수집의 '본 것' 기록이 이렇게 한 건도 안 남았다. 화면에서는 그 자리에서
 * 흐려지니 되는 것처럼 보였고, 새로고침하면 사라졌다. 관리자 알림 세 군데와
 * 온보딩 닫기도 같은 자리에서 조용히 사라지고 있었다.
 *
 * 기다릴 필요가 없는 일(본 것 표시·알림 보내기처럼 실패해도 화면이 멀쩡한 일)에만
 * 쓴다. 결과를 봐야 하면 그냥 `await` 한다.
 */
export function sendAndForget(query: PromiseLike<unknown>): void {
  void query.then(() => {}, () => {})
}
